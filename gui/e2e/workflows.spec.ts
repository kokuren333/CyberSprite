import { test, expect } from '@playwright/test';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve('..');
test('W2 pointer-up commits one line; W1 external CLI commit refreshes canvas and activity', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('/#playwright-fixture-token');
  await expect(page.getByTestId('sprite-canvas')).toBeVisible();
  await expect(page.getByTestId('revision')).toHaveText('r0');
  await page.getByRole('button', { name: 'Line', exact: true }).click();
  const canvas = page.getByTestId('sprite-canvas'), box = (await canvas.boundingBox())!;
  await page.mouse.move(box.x + 12, box.y + 20);
  await page.mouse.down();
  await page.mouse.move(box.x + 52, box.y + 20, { steps: 5 });
  await expect(page.getByTestId('revision')).toHaveText('r0');
  await page.mouse.up();
  await expect(page.getByTestId('revision')).toHaveText('r1');
  await expect(page.locator('.activity-list')).toContainText('gui');
  const { project } = JSON.parse(readFileSync(resolve(root, '.gui-check/session.json'), 'utf8'));
  const journal = readFileSync(resolve(project, '.cybersprite/history/journal.jsonl'), 'utf8').trim().split('\n').map(v => JSON.parse(v));
  expect(journal.filter((e: any) => e.actor === 'gui')).toHaveLength(1);
  expect(journal.at(-1).ops[0].op).toBe('line');
  const before = await canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL());
  execFileSync('uv', ['run', 'cybersprite', 'op', 'set_pixel', '-p', project, '--actor', 'agent:playwright', '--args', JSON.stringify({ layer: 'L1', frame: 0, x: 8, y: 8, color: 1 })], { cwd: root });
  const committed = Date.now();
  await expect(page.getByTestId('revision')).toHaveText('r2', { timeout: 1000 });
  expect(Date.now() - committed).toBeLessThan(1000);
  await expect(page.locator('.activity-list')).toContainText('agent:playwright');
  await expect.poll(() => canvas.evaluate((el: HTMLCanvasElement) => el.toDataURL())).not.toBe(before);
  await page.keyboard.press('Control+s');
  await expect(page.getByTestId('status')).toHaveText('Saved (r2)');
  await expect(page.getByTestId('revision')).toHaveText('r2');
  expect(errors).toEqual([]);
});
test('new/open dialogs use operation schema and preserve project paths', async ({ page }) => {
  await page.goto('/#playwright-fixture-token');
  await expect(page.getByTestId('sprite-canvas')).toBeVisible();
  await page.getByText('File', { exact: true }).click();
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await expect(page.locator('dialog')).toBeVisible();
  await expect(page.getByLabel('Arguments (JSON)')).toContainText('');
  await page.getByLabel('Project path').fill(`.gui-check/dialog-${Date.now()}.csprite`);
  await page.getByLabel('Arguments (JSON)').fill(JSON.stringify({ width: 4, height: 5 }));
  await page.getByRole('button', { name: 'Apply', exact: true }).click();
  await expect(page.locator('dialog')).not.toBeVisible();
  await expect(page.locator('.status-bar')).toContainText('4×5');
});
test('W4 tag direction, finite repeat, onion frames and duration edits use real data', async ({ page }) => {
  const { project } = JSON.parse(readFileSync(resolve(root, '.gui-check/session.json'), 'utf8'));
  const op = (name: string, args: object) => execFileSync('uv', ['run', 'cybersprite', 'op', name, '-p', project, '--args', JSON.stringify(args)], { cwd: root });
  op('add_frame', { count: 2, duration_ms: 400 });
  op('add_tag', { name: 'reverse-once', from: 0, to: 2, direction: 'reverse', repeat: 1 });
  const requests: any[] = [];
  page.on('websocket', ws => ws.on('framesent', event => requests.push(JSON.parse(String(event.payload)))));
  await page.goto('/#playwright-fixture-token');
  await expect(page.getByTestId('sprite-canvas')).toBeVisible();
  await page.locator('.playback-controls select').selectOption({ label: 'reverse-once: 0–2 (reverse, 1)' });
  await page.getByRole('button', { name: 'Play', exact: true }).click();
  await expect(page.locator('.timeline-grid tbody tr:first-child td:nth-of-type(3) button')).toHaveAttribute('aria-pressed', 'true');
  await expect(page.getByRole('button', { name: 'Play', exact: true })).toBeVisible();
  await expect(page.locator('.timeline-grid tbody tr:first-child td:nth-of-type(1) button')).toHaveAttribute('aria-pressed', 'true');
  await page.getByLabel('Onion skin', { exact: true }).check();
  await expect.poll(() => requests.some(r => r.method === 'render.frame' && r.params.frames?.length === 2)).toBe(true);
  await page.getByLabel('Duration (ms) 0', { exact: true }).fill('120');
  await page.getByLabel('Duration (ms) 0', { exact: true }).blur();
  await expect.poll(() => JSON.parse(readFileSync(resolve(project, 'project.json'), 'utf8')).frames[0].duration_ms).toBe(120);
});
