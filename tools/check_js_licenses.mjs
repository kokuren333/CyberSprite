/** Fail-closed audit of every installed JS package, including nested dependencies. */
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { resolve, relative, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = resolve(fileURLToPath(new URL('../gui/', import.meta.url)));
const allowed = new Set(['MIT', 'MIT-0', '0BSD', 'BSD-2-Clause', 'BSD-3-Clause',
  'Apache-2.0', 'ISC', 'Zlib', 'HPND', 'PSF-2.0', 'Unlicense', 'CC0-1.0']);
// SPDX conjunction/disjunction: an OR needs one permitted option; AND needs all.
export function permitted(expression) {
  if (typeof expression !== 'string') return false;
  const tokens = expression.match(/\(|\)|[\w.+-]+/g) ?? [];
  if (tokens.join('') !== expression.replace(/\s/g, '')) return false;
  let pos = 0;
  function atom() {
    const t = tokens[pos++];
    if (t !== '(') return allowed.has(t);
    const v = or();
    if (tokens[pos++] !== ')') throw Error('Unclosed license expression');
    return v;
  }
  function and() { let v = atom(); while (tokens[pos] === 'AND') { pos++; const b = atom(); v = v && b; } return v; }
  function or() { let v = and(); while (tokens[pos] === 'OR') { pos++; const b = and(); v = v || b; } return v; }
  try { const v = or(); return v && pos === tokens.length; } catch { return false; }
}

async function packages(directory) {
  const found = [];
  for (const d of await readdir(directory, { withFileTypes: true })) {
    if (!d.isDirectory() || d.name.startsWith('.')) continue;
    const p = join(directory, d.name);
    if (d.name.startsWith('@')) found.push(...await packages(p));
    else {
      found.push(p);
      try { found.push(...await packages(join(p, 'node_modules'))); } catch (e) { if (e.code !== 'ENOENT') throw e; }
    }
  }
  return found;
}

const rows = [], notices = [];
for (const dir of (await packages(join(root, 'node_modules'))).sort()) {
  const pkg = JSON.parse(await readFile(join(dir, 'package.json'), 'utf8'));
  const files = (await readdir(dir)).filter(n => /^(licen[sc]e|copying)(\.|$)/i.test(n)).sort();
  // esbuild's platform package contains only a binary; its same-version wrapper
  // ships the upstream grant for that exact release. Never accept metadata alone.
  if (!files.length && pkg.name.startsWith('@esbuild/')) {
    const wrapper = JSON.parse(await readFile(join(root, 'node_modules/esbuild/package.json'), 'utf8'));
    if (wrapper.version === pkg.version) files.push(relative(dir, join(root, 'node_modules/esbuild/LICENSE.md')));
  }
  if (!files.length && pkg.name.startsWith('@rollup/rollup-')) {
    const wrapper = JSON.parse(await readFile(join(root, 'node_modules/rollup/package.json'), 'utf8'));
    if (wrapper.version === pkg.version) files.push(relative(dir, join(root, 'node_modules/rollup/LICENSE.md')));
  }
  if (!permitted(pkg.license) || !files.length) throw Error(`Unapproved/missing license: ${pkg.name}@${pkg.version}: ${pkg.license}`);
  const texts = await Promise.all(files.map(async f => (await readFile(join(dir, f), 'utf8')).replace(/\r\n?/g, '\n')));
  for (const text of texts) for (const match of text.matchAll(/^License: (.+)$/gm)) {
    if (!permitted(match[1].trim())) throw Error(`Unapproved bundled grant: ${pkg.name}: ${match[1]}`);
  }
  if (texts.some(t => /^\s*(GNU (GENERAL|LESSER|AFFERO)|Mozilla Public License)/i.test(t))) throw Error(`Disallowed license grant: ${pkg.name}`);
  // Require an actual complete grant, not metadata alone.
  if (!texts.some(t => /Permission (is hereby granted|to use)|Redistribution and use|Apache License[\s\S]*Version 2\.0|Creative Commons Zero/i.test(t))) throw Error(`Unrecognized grant: ${pkg.name}`);
  const hash = createHash('sha256').update(texts.join('\n')).digest('hex');
  rows.push(`| ${pkg.name} | ${pkg.version} | ${pkg.license} | ${files.map(f => f.replaceAll('\\', '/')).join(', ')} | ${hash} |`);
  notices.push(`\n## ${pkg.name} ${pkg.version}\n\n${texts.join('\n')}\n`);
}
const report = '# JavaScript dependency licenses\n\nGenerated by `node tools/check_js_licenses.mjs` from installed packages.\nAll direct and transitive runtime/build/test dependencies on this platform are included.\nFull grants: `LICENSES_JS.txt`. Optional packages for other platforms must be audited on that platform.\n\n| Package | Version | SPDX | License files | SHA-256 |\n|---|---|---|---|---|\n' + rows.join('\n') + '\n';
const outputs = [['THIRD_PARTY_JS.md', report], ['LICENSES_JS.txt', notices.join('')]];
for (const [file, contents] of outputs) {
  const target = join(root, file);
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== contents) throw Error(`${relative(root, target)} is stale; regenerate and inspect licenses.`);
  } else await writeFile(target, contents, 'utf8');
}
console.log(`Approved ${rows.length} installed JS packages; opened and checked license grants.`);
